export interface IconOption {
  emoji: string
  /** Deutsche und englische Suchwörter, vereinfacht. Gesucht wird in beiden Sprachen. */
  keywords: string
  /** Erstes Suchwort je Sprache, als Beschriftung für Bildschirmleser. */
  labels: Record<Lang, string>
}

export const ICON_OPTIONS: IconOption[] = ICONS.filter(([e], i) => ICONS.findIndex(([x]) => x === e) === i).map(([emoji, words]) => {
  const english = ICONS_EN[emoji] ?? ''
  return {
    emoji,
    keywords: normalize(`${words} ${english}`),
    labels: { de: words.split(' ')[0], en: english.split(' ')[0] || words.split(' ')[0] },
  }
})

/** Icons, deren Suchwörter mit der Eingabe beginnen. Leere Eingabe: alle. Beschriftung in der gewählten Sprache. */
export function searchIcons(query: string, lang: Lang = 'de'): (IconOption & { label: string })[] {
  const words = normalize(query).split(' ').filter(Boolean)
  const found =
    words.length === 0
      ? ICON_OPTIONS
      : ICON_OPTIONS.filter((o) => {
          const own = o.keywords.split(' ')
          return words.every((w) => own.some((k) => k.startsWith(w)))
        })
  return found.map((o) => ({ ...o, label: o.labels[lang] }))
}
